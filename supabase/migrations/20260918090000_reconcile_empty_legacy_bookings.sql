-- Existing modern audit triggers are retained. Install a trigger only when absent.
do $$
begin
  if not exists(select 1 from pg_trigger where tgrelid='public.bookings'::regclass
    and not tgisinternal and tgname='trigger_booking_audit_log') then
    execute $ddl$
      create function public.log_calendar_booking_changes() returns trigger
      language plpgsql security definer set search_path=pg_catalog,public as $body$
      declare changes jsonb := '{}'::jsonb; key text;
      begin
        if tg_op='UPDATE' then
          for key in select jsonb_object_keys(to_jsonb(new)) loop
            if (to_jsonb(old)->key) is distinct from (to_jsonb(new)->key) then
              changes := jsonb_set(changes,array[key],jsonb_build_object('old',to_jsonb(old)->key,'new',to_jsonb(new)->key));
            end if;
          end loop;
          insert into public.booking_logs(booking_id,action,old_data,new_data,changed_fields,performed_by)
          values(new.id,'UPDATE',to_jsonb(old),to_jsonb(new),changes,auth.uid());
        elsif tg_op='INSERT' then
          insert into public.booking_logs(booking_id,action,new_data,performed_by)
          values(new.id,'INSERT',to_jsonb(new),auth.uid());
        end if;
        return new;
      end;
      $body$;
    $ddl$;
    create trigger trigger_booking_audit_log after insert or update on public.bookings
      for each row execute function public.log_calendar_booking_changes();
  end if;
end;
$$;
notify pgrst, 'reload schema';
