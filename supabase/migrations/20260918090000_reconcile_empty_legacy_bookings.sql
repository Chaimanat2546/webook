-- Upgrade only an EMPTY legacy booking schema. Preserve table identities and RLS.
do $$
begin
  if exists(select 1 from information_schema.columns where table_schema='public'
    and table_name='bookings' and column_name='id' and data_type='uuid') then
    lock table public.bookings, public.booking_logs in access exclusive mode;
    if exists(select 1 from public.bookings) or exists(select 1 from public.booking_logs) then
      raise exception 'Legacy bookings must be empty; populated databases require an explicit ID mapping';
    end if;
    alter table public.bookings alter column id drop default;
    alter table public.bookings alter column id type bigint using null::bigint;
    alter table public.bookings alter column id add generated by default as identity;
    alter table public.bookings rename column listings_id to listing_id;
    alter table public.bookings rename column house_id to houseid;
    alter table public.bookings rename column codebooking to booking_code;
    alter table public.bookings alter column booking_code type varchar(50);
    alter table public.bookings alter column booking_code set not null;
    alter table public.bookings alter column listing_id set not null;
    alter table public.bookings add column customer_id bigint,
      add column booking_type varchar(30) default 'booking',
      add column status varchar(50) default 'waiting',
      add column price_sell numeric default 0, add column price_max numeric default 0,
      add column deposit_amount numeric default 0, add column extra_charge numeric default 0,
      add column quantity integer default 1, add column note text,
      add column created_by uuid references auth.users(id),
      add column created_at timestamptz default now(), add column updated_at timestamptz default now();
    alter table public.bookings add constraint bookings_booking_code_key unique(booking_code);
    alter table public.bookings add constraint bookings_listing_id_fkey foreign key(listing_id) references public.listings(id) on delete cascade;
    alter table public.bookings drop constraint no_overlapping_bookings;
    alter table public.bookings add constraint no_overlapping_bookings exclude using gist
      (listing_id with =, daterange(check_in,check_out,'[)') with &&)
      where (status not in ('cancelled','rejected'));
    alter table public.booking_logs alter column booking_id type bigint using null::bigint;
    alter table public.booking_logs alter column changed_by drop not null;
    alter table public.booking_logs add column old_data jsonb, add column new_data jsonb,
      add column changed_fields jsonb, add column performed_by uuid references auth.users(id);
    alter table public.booking_logs add constraint booking_logs_booking_id_fkey
      foreign key(booking_id) references public.bookings(id) on delete cascade;
  end if;
end;
$$;

