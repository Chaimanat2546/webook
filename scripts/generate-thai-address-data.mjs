import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const sourceDirectory = path.join(process.cwd(), "data", "geothai", "v4");
const outputFile = path.join(process.cwd(), "server", "geography", "thai-address-data.generated.ts");

function readJson(file) {
  return readFile(path.join(sourceDirectory, file), "utf8").then((content) => JSON.parse(content));
}

function postalCode(value) {
  const normalized = String(value).padStart(5, "0");
  if (!/^\d{5}$/.test(normalized)) throw new Error(`Invalid postal code: ${String(value)}`);
  return normalized;
}

function assertArray(value, name) {
  if (!Array.isArray(value)) throw new Error(`${name} must be an array`);
  return value;
}

function option(record, kind) {
  if (!Number.isInteger(record?.code) || typeof record?.name_th !== "string") throw new Error(`Invalid ${kind}`);
  return { code: record.code, nameTh: record.name_th };
}

const [geo, postalLookup] = await Promise.all([readJson("geo.json"), readJson("postal_lookup.json")]);
const provinces = [];
const districtsByProvince = {};
const subdistrictsByDistrict = {};
const districtPostcodes = new Map();
const subdistrictPostcodes = new Map();

for (const provinceRecord of assertArray(geo, "geo")) {
  const province = option(provinceRecord, "province");
  provinces.push(province);
  const districts = [];
  districtsByProvince[province.code] = districts;
  for (const districtRecord of assertArray(provinceRecord.districts, "districts")) {
    const district = option(districtRecord, "district");
    const subdistricts = [];
    subdistrictsByDistrict[district.code] = subdistricts;
    districts.push({ ...district, provinceCode: province.code, postalCodes: [] });
    for (const subdistrictRecord of assertArray(districtRecord.subdistricts, "subdistricts")) {
      const subdistrict = option(subdistrictRecord, "subdistrict");
      const code = postalCode(subdistrictRecord.postal_code);
      subdistricts.push({ ...subdistrict, provinceCode: province.code, districtCode: district.code, postalCodes: [code] });
      districtPostcodes.set(district.code, new Set([...(districtPostcodes.get(district.code) ?? []), code]));
      subdistrictPostcodes.set(subdistrict.code, new Set([...(subdistrictPostcodes.get(subdistrict.code) ?? []), code]));
    }
  }
}

for (const districts of Object.values(districtsByProvince)) {
  for (const district of districts) district.postalCodes = [...(districtPostcodes.get(district.code) ?? [])].sort();
}
for (const subdistricts of Object.values(subdistrictsByDistrict)) {
  for (const subdistrict of subdistricts) subdistrict.postalCodes = [...(subdistrictPostcodes.get(subdistrict.code) ?? [])].sort();
}

const candidatesByPostalCode = {};
for (const [rawPostalCode, row] of Object.entries(postalLookup)) {
  const code = postalCode(row?.postal_code ?? rawPostalCode);
  const candidates = assertArray(row?.addresses, `postal lookup ${code}`).map((address) => ({
    province: { code: address.province_code, nameTh: address.province_name_th },
    district: { code: address.district_code, nameTh: address.district_name_th },
    subdistrict: { code: address.subdistrict_code, nameTh: address.subdistrict_name_th },
    postalCode: code,
  }));
  candidatesByPostalCode[code] = candidates;
}

const data = { provinces, districtsByProvince, subdistrictsByDistrict, candidatesByPostalCode };
const output = `// Generated by scripts/generate-thai-address-data.mjs. Do not edit manually.\nimport type { ThaiAddressDataIndex } from "./thai-address-types.ts";\n\nexport const thaiAddressData: ThaiAddressDataIndex = ${JSON.stringify(data)};\n`;
await writeFile(outputFile, output, "utf8");
