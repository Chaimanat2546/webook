import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { test } from "node:test";

test("comparison UI distinguishes complete, partial, failed, zero and ongoing reports per website", () => {
  const output = execFileSync(process.execPath, ["--loader", "./tests/tsx-loader.mjs", "./tests/fixtures/website-period-comparison-render.mjs"], { cwd: process.cwd(), encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
  const html = JSON.parse(output) as Record<string, string>;
  assert.match(html.yearLegend, /2568/);
  assert.match(html.yearLegend, /2569/);
  assert.match(html.normalControls, /เพิ่มชุดเปรียบเทียบ/);
  assert.doesNotMatch(html.normalControls, /ช่วงวันที่ชุดหลัก|role="group"/, "the add control must not recreate primary-date or website rows");
  assert.equal((html.comparisonControls.match(/role="group"/g) ?? []).length, 0, "website visibility stays in the original chart legend");
  assert.doesNotMatch(html.comparisonControls, /ช่วงวันที่ชุดหลัก/);
  assert.match(html.comparisonControls, /ช่วงวันที่ชุดเปรียบเทียบ/);
  assert.match(html.hiddenNormalDetail, /เว็บไซต์นี้ถูกซ่อนในกราฟ/);
  assert.doesNotMatch(html.hiddenNormalDetail, /ยังโหลดข้อมูลกราฟไม่ได้|aria-label="กราฟเข้าชมและกดติดต่อรายวัน"/);
  assert.doesNotMatch(html.normalControls, /เว็บไซต์ชุดหลัก:|ทุกเว็บไซต์|role="dialog"/);
  assert.doesNotMatch(html.normalControls, /role="switch"|เทียบช่วงก่อนหน้า/);
  assert.match(html.crossSites, /Website a/);
  assert.match(html.crossSites, /Website b/);
  assert.doesNotMatch(html.crossSites, /โหลดไม่ครบ|โหลดไม่ได้|ข้อมูลไม่ครบ/, "an unselected site is not a source failure");
  assert.match(html.complete, /\+50\.0%/);
  assert.doesNotMatch(html.complete, /7\/7|2\/2|ข้อมูลครบ|จำนวนวันเท่ากัน|แกนนอนใช้วันที่/);
  assert.match(html.partial, /ข้อมูลไม่ครบ/);
  assert.match(html.partialDetails, /1\/2.*วัน/);
  assert.match(html.partialDetails, /ยอดเท่าที่มีข้อมูล/);
  assert.match(html.partialDetails, /ยังเทียบไม่ได้/);
  assert.doesNotMatch(html.partial, /\+50\.0%/);
  assert.match(html.failed, /โหลดไม่ได้/);
  assert.match(html.failed, /30/);
  assert.match(html.failed, /—/);
  assert.match(html.zero, /เพิ่ม 30 ครั้งจากฐาน 0/);
  assert.doesNotMatch(html.zero, /Infinity|NaN/);
  assert.match(html.ongoing, /ยังไม่จบวัน/);
  assert.doesNotMatch(html.ongoing, /\+50\.0%/);
  assert.match(html.ongoingPartial, /ข้อมูลไม่ครบ/);
  assert.match(html.ongoingPartialDetails, /ยังไม่สิ้นสุดวัน/);
  assert.match(html.ongoingPartialDetails, /ยอดเท่าที่มีข้อมูล/);
  assert.doesNotMatch(html.ongoingPartial, /\+50\.0%/);
  assert.match(html.total, /Website a/);
  assert.match(html.total, /Website b/);
  assert.match(html.total, /\+50\.0%/);
  assert.match(html.total, /โหลดไม่ได้/);
  assert.equal((html.unselectedPartial.match(/>ข้อมูลไม่ครบ<\/span>/g) ?? []).length, 2, "both desktop and mobile disclose incomplete current totals for an unselected site");
  assert.match(html.fallbackPartial, /role="status"[^>]*>ข้อมูลบางเว็บไซต์ไม่ครบ/);
  assert.match(html.overview, /เว็บไซต์ในกราฟเปรียบเทียบ/);
  assert.match(html.overview, /Website a/);
  assert.match(html.overview, /Website b/);
  assert.doesNotMatch(html.overview, /role="combobox"|เว็บไซต์ที่เปรียบเทียบ/);
  assert.match(html.complete, /กราฟรายวันเทียบชุดข้อมูลรายเว็บไซต์/);
  assert.doesNotMatch(html.complete, /เว็บไซต์ในกราฟเปรียบเทียบ/);
  const detailLinks = [...html.detailNavigation.matchAll(/href="([^"]+)"[^>]*>ดูทั้งหมด</g)];
  assert.equal(detailLinks.length, 1);
  assert.match(detailLinks[0][1], /analyticsCompare=previous/);
  const pageLinks = [...html.listNavigation.matchAll(/href="([^"]+)"/g)].filter(([, href]) => href.includes("page_a=2"));
  assert.ok(pageLinks.length > 0, "fixture renders pagination links");
  for (const [, href] of pageLinks) assert.match(href, /analyticsCompare=previous/);
});
